#!/usr/bin/env node
// Turns content/challenges/<slug>/ (challenge.json + approved night-NN.md
// files) into the challenge catalog migration. Draft or in-review sessions are
// refused unless --allow-draft (local development only). Run through
// `pnpm content:generate-challenge-seed`; requires content-tools to be built.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = resolve(process.cwd());
const challengesRoot = join(root, "content", "challenges");
const outputPath = join(root, "supabase", "migrations", "20260812140000_challenge_catalog.sql");
const allowDraft = process.argv.includes("--allow-draft");
const checkOnly = process.argv.includes("--check");

const tools = await import(
  pathToFileURL(join(root, "packages", "content-tools", "dist", "index.js")).href
);

const statements = [];
for (const dir of readdirSync(challengesRoot, { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  const dirPath = join(challengesRoot, dir.name);
  const metaPath = join(dirPath, "challenge.json");
  if (!existsSync(metaPath)) fail(`${dir.name}: missing challenge.json`);
  const meta = JSON.parse(readFileSync(metaPath, "utf8"));
  for (const field of ["slug", "title", "start_date", "nights"]) {
    if (meta[field] === undefined) fail(`${dir.name}/challenge.json: missing ${field}`);
  }
  if (meta.slug !== dir.name) fail(`${dir.name}: challenge.json slug mismatch (${meta.slug})`);

  statements.push(
    `insert into public.challenges (slug, title, tagline, start_date, nights, price_display, is_published)
values (${lit(meta.slug)}, ${lit(meta.title)}, ${lit(meta.tagline ?? "")}, ${lit(meta.start_date)}, ${Number(meta.nights)}, ${lit(meta.price_display ?? "")}, ${meta.is_published === true})
on conflict (slug) do update set
  title = excluded.title, tagline = excluded.tagline, start_date = excluded.start_date,
  nights = excluded.nights, price_display = excluded.price_display, is_published = excluded.is_published;`,
  );

  const nightFiles = readdirSync(dirPath)
    .filter((file) => /^night-\d{2}\.md$/.test(file))
    .sort();
  for (const file of nightFiles) {
    const source = readFileSync(join(dirPath, file), "utf8");
    const issues = tools.validateMarkdownDocument(source, `${dir.name}/${file}`);
    if (issues.length > 0) fail(issues.join("\n"));
    const { frontmatter, body } = tools.parseFrontmatter(source);
    if (frontmatter.review_status !== "approved" && !allowDraft) {
      fail(`${dir.name}/${file}: review_status is '${frontmatter.review_status}', not approved`);
    }
    const content = parseSessionBody(body, `${dir.name}/${file}`);
    statements.push(
      `insert into public.challenge_sessions
  (challenge_id, night, title, deity_focus, estimated_minutes, content, review_status, reviewed_by)
select c.id, ${Number(frontmatter.night)}, ${lit(frontmatter.session_title)}, ${lit(frontmatter.deity_focus)}, ${Number(frontmatter.estimated_minutes)}, ${lit(JSON.stringify(content))}::jsonb, ${lit(frontmatter.review_status)}, ${lit(frontmatter.reviewed_by ?? "")}
from public.challenges c where c.slug = ${lit(meta.slug)}
on conflict (challenge_id, night) do update set
  title = excluded.title, deity_focus = excluded.deity_focus,
  estimated_minutes = excluded.estimated_minutes, content = excluded.content,
  review_status = excluded.review_status, reviewed_by = excluded.reviewed_by;`,
    );
  }
  console.log(
    `${meta.slug}: ${nightFiles.length} session(s), published=${meta.is_published === true}`,
  );
}

const sql = `-- Generated by scripts/generate-challenge-seed.mjs — do not edit by hand.
-- Source of truth: content/challenges/**. Regenerate after content changes.

${statements.join("\n\n")}

-- Down:
--   delete from public.challenge_sessions;
--   delete from public.challenges;
`;

if (checkOnly) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
  if (current !== sql)
    fail("challenge catalog migration is stale — run pnpm content:generate-challenge-seed");
  console.log("challenge catalog migration is up to date");
} else {
  writeFileSync(outputPath, sql);
  console.log(`wrote ${outputPath}`);
}

function parseSessionBody(body, displayFile) {
  const sections = {};
  for (const match of body.matchAll(/^##\s+(.+?)\s*$\r?\n([\s\S]*?)(?=^##\s+|$(?![\s\S]))/gm)) {
    sections[match[1]] = match[2].trim();
  }
  const shlokaBlocks = [];
  const labels = /^\*\*(Devanagari|IAST|Say it|Meaning|Source):\*\*\s+(.+)$/gm;
  let block = {};
  for (const match of (sections.Shloka ?? "").matchAll(labels)) {
    const key = {
      Devanagari: "devanagari",
      IAST: "iast",
      "Say it": "say_it",
      Meaning: "meaning",
      Source: "source",
    }[match[1]];
    if (key === "devanagari" && block.devanagari) {
      shlokaBlocks.push(block);
      block = {};
    }
    block[key] = match[2].trim();
  }
  if (block.devanagari) shlokaBlocks.push(block);
  if (shlokaBlocks.length === 0) fail(`${displayFile}: no shloka blocks parsed`);
  return {
    tonight: sections.Tonight ?? "",
    shloka: shlokaBlocks,
    meaning: sections.Meaning ?? "",
    practice: sections.Practice ?? "",
    tradition_notes: sections["Tradition notes"] ?? "",
    reflection: sections.Reflection ?? "",
  };
}

function lit(value) {
  return `'${String(value ?? "").replaceAll("'", "''")}'`;
}

function fail(message) {
  console.error(message);
  process.exit(1);
}
